  function seedProcessingParametersSnapshot(profile) {
    var chunking = profile && profile.chunking || {};
    var snapshot = {
      mode: chunking.mode,
      maxChars: chunking.maxChars,
      overlapPercent: chunking.overlapPercent,
      separator: chunking.separator,
      separatorType: chunking.separatorType,
      separatorPreset: chunking.separatorPreset,
      customSeparator: chunking.customSeparator,
      pagesPerChunk: chunking.pagesPerChunk,
      longDocumentFallback: chunking.longDocumentFallback,
      mergeShortChunks: chunking.mergeShortChunks,
      includeContext: chunking.includeContext,
      indexContent: deepClone(profile.indexContent || {})
    };
    if (chunking.mode === "semantic") {
      snapshot.semanticSensitivity = chunking.semanticSensitivity;
      snapshot.breakpointPercentile = chunking.breakpointPercentile;
      snapshot.semanticMinChars = chunking.semanticMinChars;
      snapshot.sentenceWindow = chunking.sentenceWindow;
      snapshot.fallbackMode = chunking.fallbackMode;
    }
    return snapshot;
  }

